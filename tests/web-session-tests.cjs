const assert=require('node:assert/strict');
const ws=require('../desktop/web-session.cjs');
const site='https://l.xmu.edu.my';const now=Date.UTC(2026,10,24,4,0,0);
assert.equal(ws.keyWaitMs(0,now),0);
assert.equal(ws.keyWaitMs(now-60000,now),5*60000);
assert.equal(ws.keyWaitMs(now-7*60000,now),0);
assert.equal(ws.keyWaitMs(now+60000,now),0,'future timestamps (clock change) must not block');
assert.equal(ws.isSignedInUrl(site+'/my/',site),true);
assert.equal(ws.isSignedInUrl(site+'/mod/assign/view.php?id=42',site),true);
assert.equal(ws.isSignedInUrl(site+'/login/index.php',site),false);
assert.equal(ws.isSignedInUrl(site+'/auth/oidc/login.php',site),false);
assert.equal(ws.isSignedInUrl('https://sso.example.edu/authorize',site),false,'external SSO is not a signed-in Moodle page');
assert.equal(ws.isSignedInUrl('not a url',site),false);
const c=ws.persistentCookie({name:'MoodleSession',value:'v',domain:'l.xmu.edu.my',path:'/',secure:true,httpOnly:true,session:true,sameSite:'unspecified'},site,now);
assert.equal(c.url,site+'/');assert.equal(c.expirationDate,Math.floor(now/1000)+ws.COOKIE_LIFETIME_S);assert.equal(c.sameSite,undefined);assert.equal(c.domain,undefined);
assert.equal(ws.persistentCookie({name:'x',value:'v',domain:'.xmu.edu.my',path:'/'},site,now).domain,'.xmu.edu.my');
assert.equal(ws.persistentCookie({name:'x',value:'v',domain:'evil.example',path:'/'},site,now),null);
assert.match(ws.describeFailure({code:'autologinkeygenerationlockout'}).message,/6 分钟/);
assert.match(ws.describeFailure(null,90000).message,/2 分钟/);
assert.equal(ws.describeFailure({code:'invalidprivatetoken'}).code,'invalidprivatetoken');
console.log('PASS: autologin rate-limit wait, signed-in page detection incl. SSO, cookie persistence scope, failure messages.');
